// Generates the VSM Godavari Foods logo set (text converted to outlines so files work everywhere).
// Run: node scripts/build-logo.mjs   (needs python3 + fonttools and dev deps: @fontsource/fraunces, @fontsource/dm-sans)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { execFileSync } from "node:child_process";

const fraunces = "node_modules/@fontsource/fraunces/files/fraunces-latin-800-normal.woff";
const dmsans = "node_modules/@fontsource/dm-sans/files/dm-sans-latin-700-normal.woff";

const C = { maroon: "#7A1C1C", chilli: "#C0321F", turmeric: "#E2A425", leaf: "#2F6B3A", cream: "#FBF1DE", ink: "#2A1210" };

function textPath(fontFile, text, x, y, size, tracking = 0) {
  const out = execFileSync("python3", ["scripts/text-to-path.py", fontFile, text, String(size), String(tracking)]).toString();
  return JSON.parse(out);
}

// ---------- Emblem (120 x 120) ----------
const emblemInner = `
  <circle cx="60" cy="60" r="57" fill="${C.cream}"/>
  <circle cx="60" cy="60" r="57" fill="none" stroke="${C.maroon}" stroke-width="4"/>
  <circle cx="60" cy="60" r="50.5" fill="none" stroke="${C.turmeric}" stroke-width="1.4" stroke-dasharray="2.2 3.2"/>
  <!-- chilli + mango leaf behind the lid -->
  <path d="M66 31 C70 20 80 14 92 15 C86 20 79 27 72 33 Z" fill="${C.leaf}"/>
  <path d="M71 30 C76 22 82 18 90 16" stroke="#1E4A27" stroke-width="0.9" fill="none" stroke-linecap="round"/>
  <path d="M53 33 C45 31 36 26 30 17 C29 15 30.5 13.6 32 14.6 C37 21 45 25.5 54 28 Z" fill="${C.chilli}"/>
  <path d="M31 15.5 C29.5 13 30 10.5 32.5 9" stroke="${C.leaf}" stroke-width="2.4" fill="none" stroke-linecap="round"/>
  <!-- jaadi jar body -->
  <defs>
    <clipPath id="jarClip"><path d="M47 40 C47 45 40 47 34 54 C27 62 27 80 32 89 C36 96 45 99 60 99 C75 99 84 96 88 89 C93 80 93 62 86 54 C80 47 73 45 73 40 Z"/></clipPath>
  </defs>
  <path d="M47 40 C47 45 40 47 34 54 C27 62 27 80 32 89 C36 96 45 99 60 99 C75 99 84 96 88 89 C93 80 93 62 86 54 C80 47 73 45 73 40 Z" fill="${C.maroon}"/>
  <g clip-path="url(#jarClip)">
    <path d="M20 78 Q30 73 40 78 T60 78 T80 78 T100 78 V110 H20 Z" fill="${C.turmeric}"/>
    <path d="M20 86 Q30 81 40 86 T60 86 T80 86 T100 86" stroke="${C.cream}" stroke-width="2" fill="none"/>
    <path d="M20 93 Q30 88 40 93 T60 93 T80 93 T100 93" stroke="${C.cream}" stroke-width="2" fill="none"/>
    <ellipse cx="44" cy="62" rx="4" ry="9" fill="#ffffff" opacity="0.16" transform="rotate(18 44 62)"/>
  </g>
  <!-- cloth lid tied with thread -->
  <path d="M42 41 C42 31 50 26 60 26 C70 26 78 31 78 41 Z" fill="${C.chilli}"/>
  <path d="M41 41 H79 L76 46 H44 Z" fill="${C.chilli}"/>
  <rect x="43" y="39.2" width="34" height="3" rx="1.5" fill="${C.turmeric}"/>
  <circle cx="60" cy="40.7" r="2.4" fill="${C.turmeric}"/>
  <!-- label diamond -->
  <path d="M60 56 L67 64 L60 72 L53 64 Z" fill="${C.cream}"/>
  <path d="M60 60 L63.5 64 L60 68 L56.5 64 Z" fill="${C.chilli}"/>
`;
const emblem = (x = 0, y = 0, s = 1) => `<g transform="translate(${x} ${y}) scale(${s})">${emblemInner}</g>`;

// ---------- Wordmark ----------
const vsm = textPath(fraunces, "VSM", 0, 0, 64, 1);
const sub = textPath(dmsans, "GODAVARI FOODS", 0, 0, 15.5, 4.2);

// horizontal lockup
const H = 120, gap = 16;
const wx = 120 + gap;
const lockupW = Math.ceil(wx + Math.max(vsm.width, sub.width) + 4);
const horizontal = (dark = false) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${lockupW} ${H}" role="img" aria-label="VSM Godavari Foods">
  ${emblem()}
  <g transform="translate(${wx} 66)"><path d="${vsm.d}" fill="${dark ? C.cream : C.maroon}"/></g>
  <g transform="translate(${wx + 2} 92)"><path d="${sub.d}" fill="${dark ? C.turmeric : C.ink}"/></g>
  <rect x="${wx + 2}" y="100" width="${sub.width}" height="2.4" rx="1.2" fill="${C.turmeric}"/>
</svg>`;

// stacked lockup
const SW = 300;
const stacked = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SW} 250" role="img" aria-label="VSM Godavari Foods">
  ${emblem((SW - 130) / 2, 0, 130 / 120)}
  <g transform="translate(${(SW - vsm.width * 0.9) / 2} 205) scale(0.9)"><path d="${vsm.d}" fill="${C.maroon}"/></g>
  <g transform="translate(${(SW - sub.width) / 2} 234)"><path d="${sub.d}" fill="${C.ink}"/></g>
</svg>`;

const mark = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 120 120" role="img" aria-label="VSM Godavari Foods">${emblem()}</svg>`;

mkdirSync("public/brand", { recursive: true });
writeFileSync("public/brand/logo.svg", horizontal());
writeFileSync("public/brand/logo-light.svg", horizontal(true));
writeFileSync("public/brand/logo-stacked.svg", stacked);
writeFileSync("public/brand/logo-mark.svg", mark);
writeFileSync("src/app/icon.svg", mark);

// React data for the inline header logo
writeFileSync(
  "src/components/brand/logo-data.ts",
  `// generated by scripts/build-logo.mjs\nexport const EMBLEM = ${JSON.stringify(emblemInner.replace(/\s+/g, " ").trim())};\n` +
    `export const VSM_PATH = ${JSON.stringify(vsm.d)};\nexport const VSM_WIDTH = ${vsm.width.toFixed(1)};\n` +
    `export const SUB_PATH = ${JSON.stringify(sub.d)};\nexport const SUB_WIDTH = ${sub.width.toFixed(1)};\nexport const LOCKUP_WIDTH = ${lockupW};\n`,
);

// PNG exports
const png = (src, out, w, h = w) => execFileSync("rsvg-convert", ["-w", String(w), "-h", String(h), "-o", out, src]);
png("public/brand/logo-mark.svg", "public/brand/logo-mark-1024.png", 1024);
png("public/brand/logo-mark.svg", "public/icon-512.png", 512);
png("public/brand/logo-mark.svg", "public/icon-192.png", 192);
png("public/brand/logo-mark.svg", "src/app/apple-icon.png", 180);
png("public/brand/logo.svg", "public/brand/logo-1600.png", 1600, Math.round((1600 * H) / lockupW));
png("public/brand/logo-stacked.svg", "public/brand/logo-stacked-1200.png", 1200, 1000);

// Open Graph image 1200x630
const og = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 630">
  <defs><radialGradient id="g" cx="30%" cy="40%" r="80%"><stop offset="0" stop-color="#FFF8EA"/><stop offset="1" stop-color="#F3DFB8"/></radialGradient></defs>
  <rect width="1200" height="630" fill="url(#g)"/>
  <path d="M0 520 Q150 490 300 520 T600 520 T900 520 T1200 520 V630 H0 Z" fill="${C.maroon}"/>
  <path d="M0 548 Q150 518 300 548 T600 548 T900 548 T1200 548" stroke="${C.turmeric}" stroke-width="6" fill="none"/>
  ${emblem(90, 110, 2.6)}
  <g transform="translate(470 270) scale(1.9)"><path d="${vsm.d}" fill="${C.maroon}"/></g>
  <g transform="translate(476 330) scale(1.75)"><path d="${sub.d}" fill="${C.ink}"/></g>
  <g transform="translate(476 400)"><path d="${textPath(dmsans, "AUTHENTIC PICKLES · SWEETS · SNACKS", 0, 0, 22, 2).d}" fill="${C.chilli}"/></g>
</svg>`;
writeFileSync("public/brand/og.svg", og);
png("public/brand/og.svg", "public/og.png", 1200, 630);
console.log("logo set generated", { lockupW });
